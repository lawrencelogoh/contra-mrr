#!/usr/bin/env node
// Generic CSV -> Supabase importer.
//
// Usage:
//   node --env-file=.env.local scripts/import-csv.mjs <csv-file> <table-name> [batch-size]
//
// Env vars required:
//   SUPABASE_URL                 e.g. https://xxxx.supabase.co
//   SUPABASE_SERVICE_ROLE_KEY    service role key (bypasses RLS, server-side only!)
//
// Behavior:
//   - Parses any CSV (handles quoted fields, BOM).
//   - Column names are derived from the header row, lowercased and snake_cased
//     so they are valid Postgres identifiers.
//   - Rows are inserted in batches. Empty cells become null.
//   - If the table doesn't exist yet, a ready-to-run CREATE TABLE statement
//     (all columns as text) is printed for the Supabase SQL editor.

import { createReadStream } from "node:fs";
import { parse } from "csv-parse";
import { createClient } from "@supabase/supabase-js";

function snakeCase(name) {
  return name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

async function readCsv(path) {
  const records = [];
  const parser = createReadStream(path).pipe(
    parse({ columns: true, skip_empty_lines: true, bom: true, trim: true })
  );
  for await (const record of parser) {
    records.push(record);
  }
  return records;
}

function toRows(records) {
  const rawHeaders = Object.keys(records[0]);
  const columns = new Map(); // csvHeader -> dbColumn
  for (const header of rawHeaders) {
    let col = snakeCase(header) || "column";
    while ([...columns.values()].includes(col)) col = `${col}_x`;
    columns.set(header, col);
  }
  const rows = records.map((record) => {
    const row = {};
    for (const [header, col] of columns) {
      const value = record[header];
      row[col] = value === undefined || value === "" ? null : value;
    }
    return row;
  });
  return { rows, columns: [...columns.values()], mapping: columns };
}

function suggestCreateTable(table, columns) {
  const cols = ["id bigint generated by default as identity primary key"]
    .concat(columns.map((c) => `${c} text`))
    .concat(["created_at timestamptz not null default now()"]);
  return `create table if not exists ${table} (\n  ${cols.join(",\n  ")}\n);`;
}

async function insertBatches(supabase, table, rows, batchSize) {
  let inserted = 0;
  for (let i = 0; i < rows.length; i += batchSize) {
    const batch = rows.slice(i, i + batchSize);
    const { error } = await supabase.from(table).insert(batch);
    if (error) {
      console.error(`Batch starting at row ${i + 1} failed:`, error.message);
      throw error;
    }
    inserted += batch.length;
    console.log(`Inserted ${inserted}/${rows.length}`);
  }
  return inserted;
}

export { snakeCase, readCsv, toRows, suggestCreateTable };

const isDirectRun =
  process.argv[1] &&
  import.meta.url === new URL(`file://${process.argv[1]}`).href;

if (isDirectRun) {
  await main();
}

async function main() {
  const args = process.argv.slice(2);
  const [csvPath, tableName, batchSizeArg] = args;

  if (!csvPath || !tableName) {
    console.error(
      "Usage: node --env-file=.env.local scripts/import-csv.mjs <csv-file> <table-name> [batch-size]"
    );
    process.exit(1);
  }

  const batchSize = Number(batchSizeArg) || 500;

  const supabaseUrl = process.env.SUPABASE_URL;
  const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!supabaseUrl || !supabaseKey) {
    console.error(
      "Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in environment."
    );
    process.exit(1);
  }

  const supabase = createClient(supabaseUrl, supabaseKey);

  const records = await readCsv(csvPath);
  if (records.length === 0) {
    console.error("CSV has no data rows.");
    process.exit(1);
  }

  const { rows, columns, mapping } = toRows(records);
  console.log(`Parsed ${rows.length} rows from ${csvPath}`);
  console.log("Column mapping:", Object.fromEntries(mapping));

  try {
    await insertBatches(supabase, tableName, rows, batchSize);
    console.log(`Done. ${rows.length} rows written to "${tableName}".`);
  } catch (error) {
    if (error.code === "PGRST205" || /does not exist/i.test(error.message)) {
      console.error(`\nTable "${tableName}" seems to be missing.`);
      console.error("Run this in the Supabase SQL editor, then re-run:\n");
      console.error(suggestCreateTable(tableName, columns));
    } else {
      console.error(error);
    }
    process.exit(1);
  }
}
